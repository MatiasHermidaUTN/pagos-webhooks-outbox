-- Estado consolidado de cada pago, con una version que sube en cada cambio: una fila por payment_id.
CREATE TABLE payment (
    payment_id  VARCHAR(64)               PRIMARY KEY,
    status      VARCHAR(20)               NOT NULL
        CHECK (status IN ('PENDING', 'AUTHORIZED', 'CAPTURED', 'FAILED', 'REFUNDED')),
    amount      NUMERIC(19, 2)            NOT NULL,
    currency    VARCHAR(3)                NOT NULL,
    version     BIGINT                    NOT NULL DEFAULT 1,
    created_at  TIMESTAMP WITH TIME ZONE  NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE  NOT NULL
);

-- Historial: todo evento recibido, tambien los que no cambiaron el estado.
-- event_id UNIQUE es la clave de idempotencia (PayGate reintenta con el mismo event_id).
CREATE TABLE payment_event (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id         VARCHAR(64)              NOT NULL UNIQUE,
    payment_id       VARCHAR(64)              NOT NULL REFERENCES payment (payment_id),
    status           VARCHAR(20)              NOT NULL
        CHECK (status IN ('PENDING', 'AUTHORIZED', 'CAPTURED', 'FAILED', 'REFUNDED')),
    amount           NUMERIC(19, 2)           NOT NULL,
    currency         VARCHAR(3)               NOT NULL,
    event_timestamp  TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    outcome          VARCHAR(10)              NOT NULL CHECK (outcome IN ('APPLIED', 'IGNORED'))
);

CREATE INDEX idx_payment_event_history ON payment_event (payment_id, event_timestamp, id);
